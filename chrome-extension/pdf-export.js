class PDFExport {
  constructor() {
    this.canvas = null;
    this.ctx = null;
    this.pageWidth = 595.28; // A4 width in points
    this.pageHeight = 841.89; // A4 height in points
    this.margin = 40;
    this.init();
  }

  init() {
    this.canvas = document.createElement('canvas');
    this.ctx = this.canvas.getContext('2d');
  }

  async exportImageToPDF(imageData, options = {}) {
    const {
      filename = 'screenshot',
      title = 'Screenshot Export',
      description = '',
      includeMetadata = true,
      quality = 0.95
    } = options;

    try {
      // Create PDF content
      const pdfContent = await this.createPDFContent(imageData, {
        title,
        description,
        includeMetadata
      });

      // Convert to blob and download
      const blob = new Blob([pdfContent], { type: 'application/pdf' });
      const url = URL.createObjectURL(blob);
      
      const link = document.createElement('a');
      link.href = url;
      link.download = `${filename}-${new Date().toISOString().slice(0, 19).replace(/:/g, '-')}.pdf`;
      link.click();
      
      URL.revokeObjectURL(url);
      
      return { success: true, filename: link.download };
    } catch (error) {
      console.error('Error exporting to PDF:', error);
      throw error;
    }
  }

  async createPDFContent(imageData, options) {
    // Simple PDF creation - in a real implementation, you'd use a library like jsPDF
    // This is a basic implementation for demonstration
    
    const img = await this.loadImage(imageData);
    const { width, height } = this.calculateImageDimensions(img);
    
    // Create basic PDF structure
    const pdfData = this.createBasicPDF(img, width, height, options);
    
    return pdfData;
  }

  loadImage(imageData) {
    return new Promise((resolve, reject) => {
      const img = new Image();
      img.onload = () => resolve(img);
      img.onerror = reject;
      img.src = imageData;
    });
  }

  calculateImageDimensions(img) {
    const maxWidth = this.pageWidth - (this.margin * 2);
    const maxHeight = this.pageHeight - (this.margin * 3); // Extra margin for text
    
    let width = img.width;
    let height = img.height;
    
    // Scale to fit page
    const widthRatio = maxWidth / width;
    const heightRatio = maxHeight / height;
    const ratio = Math.min(widthRatio, heightRatio);
    
    if (ratio < 1) {
      width *= ratio;
      height *= ratio;
    }
    
    return { width, height };
  }

  createBasicPDF(img, width, height, options) {
    // This is a simplified PDF creation
    // In a real implementation, use jsPDF or similar library
    
    const canvas = document.createElement('canvas');
    canvas.width = this.pageWidth;
    canvas.height = this.pageHeight;
    const ctx = canvas.getContext('2d');
    
    // White background
    ctx.fillStyle = '#ffffff';
    ctx.fillRect(0, 0, canvas.width, canvas.height);
    
    // Add title if provided
    if (options.title) {
      ctx.fillStyle = '#000000';
      ctx.font = '16px Arial';
      ctx.fillText(options.title, this.margin, this.margin + 20);
    }
    
    // Add description if provided
    if (options.description) {
      ctx.fillStyle = '#666666';
      ctx.font = '12px Arial';
      const lines = this.wrapText(ctx, options.description, this.pageWidth - (this.margin * 2));
      lines.forEach((line, index) => {
        ctx.fillText(line, this.margin, this.margin + 50 + (index * 15));
      });
    }
    
    // Add image
    const imageY = this.margin + (options.title ? 30 : 0) + (options.description ? 80 : 0);
    const imageX = (this.pageWidth - width) / 2; // Center image
    
    ctx.drawImage(img, imageX, imageY, width, height);
    
    // Add metadata if requested
    if (options.includeMetadata) {
      const metadataY = imageY + height + 20;
      ctx.fillStyle = '#999999';
      ctx.font = '10px Arial';
      ctx.fillText(`Created: ${new Date().toLocaleString()}`, this.margin, metadataY);
      ctx.fillText(`Size: ${img.width} x ${img.height}px`, this.margin, metadataY + 15);
      ctx.fillText('Generated by Screen Recorder Pro', this.margin, metadataY + 30);
    }
    
    // Convert canvas to PDF-like data
    return canvas.toDataURL('image/png');
  }

  wrapText(ctx, text, maxWidth) {
    const words = text.split(' ');
    const lines = [];
    let currentLine = words[0];

    for (let i = 1; i < words.length; i++) {
      const word = words[i];
      const width = ctx.measureText(currentLine + ' ' + word).width;
      if (width < maxWidth) {
        currentLine += ' ' + word;
      } else {
        lines.push(currentLine);
        currentLine = word;
      }
    }
    lines.push(currentLine);
    return lines;
  }

  // Export multiple images as multi-page PDF
  async exportMultipleImagesToPDF(images, options = {}) {
    const {
      filename = 'screenshots',
      title = 'Screenshot Collection',
      includeMetadata = true
    } = options;

    try {
      // For multiple images, we'd create multiple pages
      // This is a simplified version
      const pdfPages = [];
      
      for (let i = 0; i < images.length; i++) {
        const pageContent = await this.createPDFContent(images[i], {
          title: `${title} - Page ${i + 1}`,
          includeMetadata: i === 0 // Only include metadata on first page
        });
        pdfPages.push(pageContent);
      }
      
      // Combine pages (simplified)
      const combinedPDF = pdfPages[0]; // In real implementation, properly combine pages
      
      const blob = new Blob([combinedPDF], { type: 'application/pdf' });
      const url = URL.createObjectURL(blob);
      
      const link = document.createElement('a');
      link.href = url;
      link.download = `${filename}-${new Date().toISOString().slice(0, 19).replace(/:/g, '-')}.pdf`;
      link.click();
      
      URL.revokeObjectURL(url);
      
      return { success: true, filename: link.download, pages: images.length };
    } catch (error) {
      console.error('Error exporting multiple images to PDF:', error);
      throw error;
    }
  }

  // Create PDF with annotations
  async exportAnnotatedImageToPDF(imageData, annotations, options = {}) {
    try {
      // Load the base image
      const img = await this.loadImage(imageData);
      
      // Create canvas with annotations
      const canvas = document.createElement('canvas');
      canvas.width = img.width;
      canvas.height = img.height;
      const ctx = canvas.getContext('2d');
      
      // Draw base image
      ctx.drawImage(img, 0, 0);
      
      // Draw annotations
      this.drawAnnotations(ctx, annotations);
      
      // Export the combined image as PDF
      const annotatedImageData = canvas.toDataURL('image/png');
      return this.exportImageToPDF(annotatedImageData, options);
      
    } catch (error) {
      console.error('Error exporting annotated image to PDF:', error);
      throw error;
    }
  }

  drawAnnotations(ctx, annotations) {
    annotations.forEach(annotation => {
      ctx.save();
      
      switch (annotation.type) {
        case 'pen':
          this.drawPenAnnotation(ctx, annotation);
          break;
        case 'text':
          this.drawTextAnnotation(ctx, annotation);
          break;
        case 'rectangle':
          this.drawRectangleAnnotation(ctx, annotation);
          break;
        case 'circle':
          this.drawCircleAnnotation(ctx, annotation);
          break;
        case 'arrow':
          this.drawArrowAnnotation(ctx, annotation);
          break;
        default:
          console.warn('Unknown annotation type:', annotation.type);
      }
      
      ctx.restore();
    });
  }

  drawPenAnnotation(ctx, annotation) {
    ctx.strokeStyle = annotation.color || '#ff0000';
    ctx.lineWidth = annotation.size || 3;
    ctx.lineCap = 'round';
    ctx.lineJoin = 'round';
    
    ctx.beginPath();
    annotation.points.forEach((point, index) => {
      if (index === 0) {
        ctx.moveTo(point.x, point.y);
      } else {
        ctx.lineTo(point.x, point.y);
      }
    });
    ctx.stroke();
  }

  drawTextAnnotation(ctx, annotation) {
    ctx.fillStyle = annotation.color || '#000000';
    ctx.font = `${annotation.size || 16}px ${annotation.font || 'Arial'}`;
    ctx.fillText(annotation.text, annotation.x, annotation.y);
  }

  drawRectangleAnnotation(ctx, annotation) {
    ctx.strokeStyle = annotation.color || '#ff0000';
    ctx.lineWidth = annotation.size || 2;
    
    if (annotation.fill) {
      ctx.fillStyle = annotation.fillColor || annotation.color;
      ctx.fillRect(annotation.x, annotation.y, annotation.width, annotation.height);
    }
    
    ctx.strokeRect(annotation.x, annotation.y, annotation.width, annotation.height);
  }

  drawCircleAnnotation(ctx, annotation) {
    ctx.strokeStyle = annotation.color || '#ff0000';
    ctx.lineWidth = annotation.size || 2;
    
    ctx.beginPath();
    ctx.arc(annotation.x, annotation.y, annotation.radius, 0, Math.PI * 2);
    
    if (annotation.fill) {
      ctx.fillStyle = annotation.fillColor || annotation.color;
      ctx.fill();
    }
    
    ctx.stroke();
  }

  drawArrowAnnotation(ctx, annotation) {
    ctx.strokeStyle = annotation.color || '#ff0000';
    ctx.lineWidth = annotation.size || 2;
    
    // Draw line
    ctx.beginPath();
    ctx.moveTo(annotation.startX, annotation.startY);
    ctx.lineTo(annotation.endX, annotation.endY);
    ctx.stroke();
    
    // Draw arrowhead
    const angle = Math.atan2(annotation.endY - annotation.startY, annotation.endX - annotation.startX);
    const headLength = 15;
    
    ctx.beginPath();
    ctx.moveTo(annotation.endX, annotation.endY);
    ctx.lineTo(
      annotation.endX - headLength * Math.cos(angle - Math.PI / 6),
      annotation.endY - headLength * Math.sin(angle - Math.PI / 6)
    );
    ctx.moveTo(annotation.endX, annotation.endY);
    ctx.lineTo(
      annotation.endX - headLength * Math.cos(angle + Math.PI / 6),
      annotation.endY - headLength * Math.sin(angle + Math.PI / 6)
    );
    ctx.stroke();
  }
}

// Global instance
window.pdfExport = new PDFExport();
